import { AudioRuntime, NullAudioDSPAdapter, createAudioRuntimeCommand } from './index.js';
function eq(a: unknown, b: unknown) { if (a !== b) throw new Error(`Expected ${String(b)}, received ${String(a)}`); }
function ok(v: unknown) { if (!v) throw new Error('Expected value'); }
const rt = new AudioRuntime({}, new NullAudioDSPAdapter());
rt.dispatch(createAudioRuntimeCommand('CREATE_AUDIO_CHANNEL', { channel: { id: 'ch-1', label: 'Mic 1', kind: 'mic' } }));
eq(rt.state.channels['ch-1']?.label, 'Mic 1');
rt.dispatch(createAudioRuntimeCommand('SET_CHANNEL_GAIN', { channelId: 'ch-1', gain: 0.5 }));
eq(rt.state.channels['ch-1']?.gain, 0.5);
rt.dispatch(createAudioRuntimeCommand('MUTE_CHANNEL', { channelId: 'ch-1' }));
eq(rt.state.channels['ch-1']?.muted, true);
rt.dispatch(createAudioRuntimeCommand('UNMUTE_CHANNEL', { channelId: 'ch-1' }));
eq(rt.state.channels['ch-1']?.muted, false);
rt.dispatch(createAudioRuntimeCommand('SOLO_CHANNEL', { channelId: 'ch-1' }));
eq(rt.state.channels['ch-1']?.solo, true);
rt.dispatch(createAudioRuntimeCommand('UNSOLO_CHANNEL', { channelId: 'ch-1' }));
eq(rt.state.channels['ch-1']?.solo, false);
rt.dispatch(createAudioRuntimeCommand('ASSIGN_CHANNEL_TO_BUS', { channelId: 'ch-1', busId: 'bus-a', busLabel: 'Aux A' }));
ok(rt.state.channels['ch-1']?.assignedBusIds.includes('bus-a'));
rt.dispatch(createAudioRuntimeCommand('REMOVE_CHANNEL_FROM_BUS', { channelId: 'ch-1', busId: 'bus-a' }));
eq(rt.state.channels['ch-1']?.assignedBusIds.includes('bus-a'), false);
rt.dispatch(createAudioRuntimeCommand('SET_MASTER_GAIN', { gain: 0.8 }));
eq(rt.state.mix.masterGain, 0.8);
rt.dispatch(createAudioRuntimeCommand('MUTE_MASTER'));
eq(rt.state.mix.masterMuted, true);
rt.dispatch(createAudioRuntimeCommand('UNMUTE_MASTER'));
eq(rt.state.mix.masterMuted, false);
rt.dispatch(createAudioRuntimeCommand('SET_MONITOR_SOURCE', { monitorSourceType: 'channel', monitorSourceId: 'ch-1' }));
eq(rt.state.monitor.sourceId, 'ch-1');
rt.dispatch(createAudioRuntimeCommand('CLEAR_MONITOR_SOURCE'));
eq(rt.state.monitor.sourceId, null);
const beforeDrops = rt.metrics.droppedCommands;
rt.dispatch(createAudioRuntimeCommand('SET_MASTER_GAIN', { gain: 2 }));
rt.dispatch(createAudioRuntimeCommand('SET_MONITOR_SOURCE', { monitorSourceType: 'channel', monitorSourceId: 'missing' }));
rt.dispatch({ ...createAudioRuntimeCommand('MUTE_MASTER'), runtimeHandle: undefined } as never);
ok(rt.metrics.droppedCommands >= beforeDrops + 3);
eq(rt.health.audioRuntimeUnavailable, true);
eq(rt.health.dspEngineConnected, false);
eq(rt.health.meteringUnavailable, true);
eq(rt.health.metadataOnly, true);
ok(rt.session.snapshot('validator'));
ok(rt.state.history.length > 0);
rt.session.queue.enqueue(createAudioRuntimeCommand('MUTE_MASTER'));
eq(rt.session.queue.size, 1);
rt.session.queue.clear();
eq(rt.session.queue.size, 0);
rt.dispatch(createAudioRuntimeCommand('RESET_AUDIO_MIX'));
eq(Object.keys(rt.state.channels).length, 0);
eq(rt.state.masterBus.peak, null);
console.log('Runtime audio validation passed');
